# ==================== 会话历史压缩 ====================
# 数字人对话是多轮的，但每轮只发当前这句话，模型看不到前面聊过什么。
# 记忆做法：近期几轮原文照发，更早的交给这个提示词压成一段摘要，随下一轮注入。
# 摘要不是流水账——它只留「还用得着」的东西，聊完就扔的闲话不占地方。
CHAT_SUMMARY_PROMPT = """你要把一段导游与游客的对话历史压缩成一份「交接笔记」。

输入 JSON：{ old_summary: 上一份摘要（可能为空）, turns: [{role, text}] }

输出：直接输出这份笔记的正文，不要 JSON，不要 Markdown 标题，不要解释文字。

必须留下这些内容：
1. 游客的基本情况：同行人数、身份（带老人/小孩/学生）、兴趣偏好、饮食忌口、预算与体力情况
2. 已经聊过并给出结论的景点/问题，以及结论本身（门票、开放时间、路线、注意事项）
3. 游客表达过的喜好与嫌恶（"不喜欢人多""怕爬台阶""爱吃辣"）
4. 还没解决、游客还在追问的问题
5. 已经约定好的安排或承诺（"明天早上看升旗""下午三点集合"）

硬性要求：
1. 用中文，控制在 400 字以内，宁可少写也不要注水。
2. 只写对话里真实出现过的信息，一个字都不许编。
3. 已经解决且不会再提起的寒暄、重复提问、确认语一律不写。
4. 若 old_summary 非空，把它与 turns 合并后再压缩，不要把两份内容并列堆砌。
5. 以「游客」和「导游」来称呼双方，不要用"用户""AI"。"""


